-- Regenerates supabase/schema/schema.sql.
--
-- Paste into the Supabase SQL editor (or run through the Supabase MCP), copy
-- the single `ddl` value it returns, and save it over schema.sql. Read-only.
--
-- Why this and not `supabase db dump`: the CLI needs Docker and the database
-- password; this needs neither. It covers what the app depends on — the
-- public schema's tables, constraints, indexes, RLS policies, functions and
-- triggers, plus extensions, pg_cron jobs, storage buckets and the names (never
-- the values) of Vault secrets. It does not cover grants beyond Supabase's
-- defaults or anything in the auth schema.

with
tbl as (
  select c.oid, c.relname, c.relrowsecurity
  from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
),
cols as (
  select t.relname,
         string_agg(
           format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                  case a.attidentity when 'a' then ' generated always as identity'
                                     when 'd' then ' generated by default as identity' else '' end,
                  case when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid) else '' end,
                  case when a.attnotnull then ' not null' else '' end),
           E',\n' order by a.attnum) as body
  from tbl t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
  group by t.relname
),
cons as (
  select t.relname,
         string_agg(format('  constraint %I %s', con.conname, pg_get_constraintdef(con.oid)),
                    E',\n' order by con.contype desc, con.conname) as body
  from tbl t join pg_constraint con on con.conrelid = t.oid
  group by t.relname
),
sections as (
  select 1 as ord, '' as k,
         '-- Layercade database schema snapshot, generated ' || to_char(now() at time zone 'utc', 'YYYY-MM-DD HH24:MI "UTC"') || E'.\n' ||
         E'-- Regenerate with supabase/schema/snapshot_query.sql. Reference only: not a\n' ||
         E'-- migration, and running it against a live database will fail on existing\n' ||
         E'-- objects. Changes still go through supabase/migrations/.\n' as ddl

  union all
  select 2, '', E'\n-- ─── Extensions ───────────────────────────────────────────────────────────\n\n' ||
         string_agg(format('create extension if not exists %I with schema %I;', e.extname, n.nspname), E'\n' order by e.extname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'

  -- Sequences behind plain `default nextval(...)` columns. Identity columns
  -- create their own, so those are skipped.
  union all
  select 2, '~', E'\n-- ─── Sequences ────────────────────────────────────────────────────────────\n\n' ||
         string_agg(format('create sequence if not exists public.%I;', s.relname), E'\n' order by s.relname)
  from pg_class s
  where s.relkind = 'S' and s.relnamespace = 'public'::regnamespace
    and not exists (select 1 from pg_depend d where d.objid = s.oid and d.deptype = 'i')

  union all
  select 3, t.relname,
         format(E'\n-- ─── %s ─\n\ncreate table public.%I (\n%s%s\n);\n',
                t.relname, t.relname, c.body,
                coalesce(E',\n' || k.body, '')) ||
         case when t.relrowsecurity then format(E'alter table public.%I enable row level security;\n', t.relname) else '' end
  from tbl t join cols c using (relname) left join cons k using (relname)

  union all
  select 4, '', E'\n-- ─── Indexes (beyond primary keys and unique constraints) ──────────────────\n\n' ||
         string_agg(i.indexdef || ';', E'\n' order by i.tablename, i.indexname)
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (select 1 from pg_constraint con where con.conname = i.indexname and con.connamespace = 'public'::regnamespace)

  union all
  select 5, '', E'\n-- ─── Row level security policies ──────────────────────────────────────────\n\n' ||
         string_agg(
           format('create policy %I on public.%I as %s for %s to %s%s%s;',
                  p.policyname, p.tablename, lower(p.permissive), lower(p.cmd), array_to_string(p.roles, ', '),
                  case when p.qual is not null then E'\n  using (' || p.qual || ')' else '' end,
                  case when p.with_check is not null then E'\n  with check (' || p.with_check || ')' else '' end),
           E'\n\n' order by p.tablename, p.policyname)
  from pg_policies p where p.schemaname = 'public'

  union all
  select 6, '', E'\n-- ─── Functions ────────────────────────────────────────────────────────────\n\n' ||
         string_agg(pg_get_functiondef(f.oid) || ';', E'\n' order by f.proname)
  from pg_proc f
  where f.pronamespace = 'public'::regnamespace and f.prokind = 'f'

  union all
  select 7, '', E'\n-- ─── Triggers ─────────────────────────────────────────────────────────────\n\n' ||
         string_agg(pg_get_triggerdef(tg.oid) || ';', E'\n' order by tg.tgrelid::regclass::text, tg.tgname)
  from pg_trigger tg join tbl t on t.oid = tg.tgrelid
  where not tg.tgisinternal

  union all
  select 8, '', E'\n-- ─── pg_cron jobs ─────────────────────────────────────────────────────────\n\n' ||
         coalesce(string_agg(format('select cron.schedule(%L, %L, %L);', j.jobname, j.schedule, j.command), E'\n' order by j.jobname), '-- none')
  from cron.job j

  union all
  select 9, '', E'\n-- ─── Storage buckets ──────────────────────────────────────────────────────\n\n' ||
         coalesce(string_agg(format('insert into storage.buckets (id, name, public) values (%L, %L, %s);', b.id, b.name, case when b.public then 'true' else 'false' end), E'\n' order by b.id), '-- none')
  from storage.buckets b

  union all
  select 10, '', E'\n-- ─── Vault secrets (names only; set values in the dashboard) ──────────────\n\n' ||
         coalesce(string_agg('-- ' || s.name, E'\n' order by s.name), '-- none')
  from vault.secrets s
)
select string_agg(ddl, E'\n' order by ord, k) as ddl from sections where ddl is not null;
